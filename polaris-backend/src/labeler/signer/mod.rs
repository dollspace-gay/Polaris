//! Labeler signing-key trait + custody implementations (issue #29 / REQ-11).
//!
//! Polaris's K-256 signing key is the labeler's identity: every
//! `com.atproto.label.defs::Label` row emitted on the wire is signed with
//! this key and consumers verify the signature against the public key
//! Polaris publishes in its `app.bsky.labeler.service` record. The key
//! must be guarded as one of the two most sensitive secrets the process
//! holds (the other being the moderator-session cookie key from
//! [`crate::config::SecurityConfig`]).
//!
//! # Four custody postures
//!
//! v1 ships four implementations of [`SigningKey`], selected by
//! `[labeler.signing_key] mode` at startup:
//!
//! | Mode                | At-rest defense | Code-exec defense | Restart UX        |
//! |---------------------|-----------------|-------------------|-------------------|
//! | `file-plain`        | none            | none              | zero-touch        |
//! | `passphrase-sealed` | AES-256-GCM + scrypt | none         | passphrase prompt |
//! | `os-keychain`       | OS keychain     | none              | zero-touch        |
//! | `cloud-kms-oracle`  | KMS at rest     | per-`sign()` RPC  | zero-touch        |
//!
//! `.design/polaris-proto-blue-integration.md` §B (REQ-11) is the
//! authoritative discussion of why each mode exists and what threat
//! model it covers; this module is the implementation.
//!
//! # Boot-time profile enforcement (AC-14)
//!
//! [`build_signing_key`] is a *startup-only* validator. The Bluesky
//! deployment profile explicitly disallows `file-plain` because a
//! first-party deployment running KMS infrastructure should never
//! regress to a plaintext on-disk key. The combination produces a typed
//! [`SigningError::WrongProfile`] error which the binary entrypoint
//! converts into a non-zero exit before any HTTP traffic begins.
//!
//! # Signature shape
//!
//! `sign()` returns a [`Signature`] — a newtype around `[u8; 64]`
//! holding the K-256 ECDSA compact signature as
//! `r (32 bytes, big-endian) || s (32 bytes, big-endian)`. This is the
//! exact layout the atproto label-signing contract expects (see
//! `proto_blue_crypto::K256Keypair::sign`). The S-component is low-S
//! normalised so the signature is not malleable.
//!
//! # No `Arc<Mutex<…>>`
//!
//! Every concrete signer is constructed once at startup and is
//! thereafter immutable. The factory returns `Arc<dyn SigningKey>`
//! purely so heterogeneous backends can share a storage slot; there is
//! no interior mutability and no lock. (A request-time AES-GCM nonce
//! is generated by the [`passphrase_sealed`] *write* path, not by the
//! `sign` path.)

